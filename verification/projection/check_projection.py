"""Finite-law checks, continuum replay, and adversarial certificate tests."""
import copy,itertools,json,math
from unittest.mock import patch
from cvxpy.error import SolverError
from fractions import Fraction
from pathlib import Path
from flint import arb,ctx
from partial_population.projection import (Design,Projector,B,kernel_ball,
    penalty_ball,score_ball,verify_kernel_table,verify_interval,fingerprint)

ROOT=Path(__file__).resolve().parents[2]

def multinomial(p,n):
 def rec(k,total,prefix):
  if k==1:yield prefix+[total];return
  for a in range(total+1):yield from rec(k-1,total-a,prefix+[a])
 for x in rec(len(p),n,[]):
  pr=Fraction(math.factorial(n),math.prod(math.factorial(v) for v in x))
  pr*=math.prod(a**b for a,b in zip(p,x))
  yield x,pr

def must_reject(fn):
 try:fn()
 except (ValueError,ArithmeticError,AssertionError):return
 raise AssertionError('forged certificate accepted')

def main():
 checks=0; populations=[(Fraction(1,2),Fraction(1,3),Fraction(1,6)),(Fraction(1,4),Fraction(3,4))]
 worst=0.; cover=[]
 with ctx.workprec(128):
  for n in (2,4):
   for target in ('missing_mass','discoveries'):
    d=Design(n,target,2 if target=='discoveries' else 0)
    model=Projector(d);assert verify_kernel_table(model.table)
    cache={}
    for p in populations:
     ex=[arb(0) for _ in d.scales];coverage=Fraction(0)
     for x,px in multinomial(p,n):
      phi=fingerprint(x,len(d.directions()[0][0]));key=tuple(phi)
      if key not in cache:
       cache[key]=model.interval(phi);assert verify_interval(cache[key],model.table);checks+=1
      lower,upper=cache[key]['interval']
      future=list(multinomial(p,d.m)) if target=='discoveries' else [(None,Fraction(1))]
      for y,py in future:
       z=sum(p[i] for i,c in enumerate(x) if c==0) if y is None else sum(a==0 and b>0 for a,b in zip(x,y))
       if lower<=z<=upper:coverage+=px*py
       for j,(lam,eta) in enumerate(d.directions()):
        # Enumerated fixed-count law, not generated by the Poisson identity.
        K=sum((B(pi)*kernel_ball(pi,pi,d,(lam,eta)) for pi in p),arb(0))
        value=(score_ball(phi,lam)+B(eta)*B(z)-K-penalty_ball(d)).exp()
        ex[j]+=B(px*py)*value
     for v in ex:
      assert v<=1;worst=max(worst,float(v.upper()));checks+=1
     assert coverage>=1-Fraction(d.alpha)
     cover.append({'n':n,'target':target,'population':[str(v) for v in p],'coverage':str(coverage)})
    cert=next(iter(cache.values()))
    bad=copy.deepcopy(model.table);bad['cells'][0][0]=1e-12;must_reject(lambda:verify_kernel_table(bad));checks+=1
    bad=copy.deepcopy(model.table);bad['upper'][1][0]-=10;must_reject(lambda:verify_kernel_table(bad));checks+=1
    bad=copy.deepcopy(cert);bad['interval'][1]=-1;must_reject(lambda:verify_interval(bad,model.table));checks+=1
    bad=copy.deepcopy(cert);bad['fingerprint'][0]=n+1;must_reject(lambda:verify_interval(bad,model.table));checks+=1
    for endpoint in cert['endpoints']:
     if 'q' in endpoint:
      bad=copy.deepcopy(cert);i=cert['endpoints'].index(endpoint);bad['endpoints'][i]['q'][0]+=1
      must_reject(lambda:verify_interval(bad,model.table));checks+=1
  # Nonvacuous case and zero-probability kernel limit checks.
  d=Design(1000);m=Projector(d);cert=m.interval([50]);assert verify_interval(cert,m.table)
  assert cert['interval'][1]<.5;checks+=1
  with patch.object(m.problem,'solve',side_effect=SolverError('forced failure')):
   fallback=m.interval([50])
  assert verify_interval(fallback,m.table)
  assert all('failed' in ep['solver_status'] for ep in fallback['endpoints']);checks+=1
  must_reject(lambda:Design(10,scales=('1/4',)));checks+=1
  must_reject(lambda:Design(10,m=2));checks+=1
  for target in ('missing_mass','discoveries'):
   d=Design(31,target,17 if target=='discoveries' else 0)
   for lam,eta in d.directions():
    limit=d.n*B(lam[0]).expm1()+(B(eta) if target=='missing_mass' else d.m*B(eta).expm1())
    assert kernel_ball(0,0,d,(lam,eta)).overlaps(limit);checks+=1
 result={'checks':checks,'max_enumerated_e_expectation_upper':worst,
         'exact_coverages':cover,'scope':'finite-law corroboration plus continuum and tamper checks; analytic proof supplies general coverage'}
 (ROOT/'verification/projection/results.json').write_text(json.dumps(result,indent=2)+'\n')
 print(json.dumps(result,indent=2))
if __name__=='__main__':main()
